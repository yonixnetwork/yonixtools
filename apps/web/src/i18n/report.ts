/**
 * Translation coverage, per locale: keys, completeness, provenance, review and indexable pages.
 * Rendered as docs/i18n/TRANSLATION_COVERAGE.md (npm run i18n:report) and as the password-protected
 * admin page /admin/translations/.
 */
import { LOCALES, getLocale } from "./locales";
import { PUBLISHED_LOCALES } from "./config";
import { builtLocales, localeReport, type KeyState } from "./catalogue";
import { localesOnDisk } from "./server";
import { allPages, isIndexableIn, pageId } from "./routes";

export interface CoverageRow {
  code: string;
  native: string;
  name: string;
  dir: "ltr" | "rtl";
  priority: boolean;
  published: boolean;
  built: boolean;
  hasCatalogue: boolean;
  method: string;
  translator: string;
  translatedAt: string | null;
  reviewers: string[];
  total: number;
  counts: Record<KeyState, number>;
  extra: number;
  completed: number;
  status: "SOURCE" | "NOT STARTED" | "INCOMPLETE" | "MACHINE-TRANSLATED, UNREVIEWED" | "PARTLY REVIEWED" | "HUMAN-REVIEWED";
  pagesIndexable: number;
  pagesBlocked: number;
  indexablePages: string[];
}

export function coverage(): CoverageRow[] {
  const built = new Set(builtLocales());
  const onDisk = new Set(localesOnDisk());
  const pages = allPages().filter((p) => p.kind !== "offline");
  return LOCALES.map((l) => {
    const has = l.code === "en" || onDisk.has(l.code);
    const r = localeReport(l.code);
    const completed = r.counts.machine + r.counts.unreviewed + r.counts.reviewed + r.counts.stale;
    const indexable = built.has(l.code) ? pages.filter((p) => isIndexableIn(l.code, p)).map(pageId) : [];
    const status: CoverageRow["status"] =
      l.code === "en" ? "SOURCE" : !has ? "NOT STARTED" : !r.complete ? "INCOMPLETE" : r.fullyReviewed ? "HUMAN-REVIEWED" : r.counts.reviewed > 0 ? "PARTLY REVIEWED" : "MACHINE-TRANSLATED, UNREVIEWED";
    return {
      code: l.code,
      native: l.native,
      name: l.name,
      dir: l.dir,
      priority: l.priority,
      published: PUBLISHED_LOCALES.includes(l.code),
      built: built.has(l.code),
      hasCatalogue: has,
      method: r.method,
      translator: r.translator,
      translatedAt: r.translatedAt,
      reviewers: r.reviewers,
      total: r.total,
      counts: r.counts,
      extra: r.extra.length,
      completed,
      status,
      pagesIndexable: indexable.length,
      pagesBlocked: pages.length - indexable.length,
      indexablePages: indexable,
    };
  });
}

const pct = (a: number, b: number) => (b ? `${((a / b) * 100).toFixed(1)}%` : "—");

export function coverageMarkdown(date: string): string {
  const rows = coverage();
  const pages = allPages().filter((p) => p.kind !== "offline").length;
  const lines: string[] = [];
  lines.push("# Translation coverage", "");
  lines.push(`Generated by \`npm run i18n:report\` on ${date} from the catalogues in \`apps/web/src/i18n/\`. Do not edit by hand.`, "");
  lines.push("**How to read this:**");
  lines.push("- **Machine** means translated automatically (including AI translation) and not reviewed by a person.");
  lines.push("- A page is indexable only when every key it shows has been reviewed by a named person against the current English text.");
  lines.push("- Locales that are not built have no pages at all.");
  lines.push("");
  lines.push(`Public pages per locale: ${pages} (the offline page is never indexed).`, "");
  lines.push("| Locale | Language | Status | Built | Keys | Completed | Missing | Invalid | Untranslated | Machine | Human-reviewed | Stale reviews | Reviewers | Pages indexable | Pages blocked |");
  lines.push("|---|---|---|---|--:|--:|--:|--:|--:|--:|--:|--:|---|--:|--:|");
  for (const r of rows.filter((x) => x.priority || x.hasCatalogue)) {
    lines.push(
      `| \`${r.code}\` | ${r.native} (${r.name}) | ${r.status} | ${r.built ? "yes" : "no"} | ${r.total} | ${r.code === "en" ? r.total : r.completed} (${pct(r.code === "en" ? r.total : r.completed, r.total)}) | ${r.code === "en" ? 0 : r.counts.missing} | ${r.counts.invalid} | ${r.counts.untranslated} | ${r.counts.machine} | ${r.counts.reviewed}${r.code === "en" ? " (source)" : ""} | ${r.counts.stale} | ${r.reviewers.join(", ") || "—"} | ${r.pagesIndexable} | ${r.pagesBlocked} |`,
    );
  }
  lines.push("");
  const rest = rows.filter((x) => !x.priority && !x.hasCatalogue);
  lines.push(`## The other ${rest.length} supported locales`, "");
  lines.push("These locales are registered (BCP 47 code, native name, direction, URL prefix) but have no catalogue yet: **NOT STARTED**. Nothing is built or indexed for them.", "");
  lines.push(rest.map((r) => `\`${r.code}\` ${r.native}`).join(" · "), "");
  lines.push("## Translation provenance", "");
  for (const r of rows.filter((x) => x.hasCatalogue && x.code !== "en")) lines.push(`- \`${r.code}\`: ${r.translator || "unknown"}${r.translatedAt ? `, ${r.translatedAt}` : ""} (method: ${r.method})`);
  lines.push("");
  return lines.join("\n");
}

export const localeName = (code: string) => getLocale(code).native;
